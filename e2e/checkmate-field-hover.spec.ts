import {expect,test,type Page} from '@playwright/test'

async function boot(page:Page,id='tower'){
 await page.emulateMedia({reducedMotion:'reduce'})
 await page.goto(`/?mode=checkmate&encounter=${id}&new=1`)
 await page.locator('#cm-loading').waitFor({state:'hidden'})
 await page.locator(`[data-encounter-id="${id}"]`).click()
 await page.locator('#cm-start-deployment').click()
}
const square=(page:Page,id:string)=>page.locator(`#cm-squares [data-square="${id}"]`)

test('goal and obstacle explanations use a 500ms dwell, reset between squares and dismiss on leave',async({page})=>{
 await boot(page)
 const tooltip=page.locator('#cm-unit-hover')
 await square(page,'e5').hover()
 await page.waitForTimeout(300)
 await expect(tooltip).toBeHidden()
 await expect(tooltip).toBeVisible({timeout:500})
 await expect(tooltip).toContainText('Encounter goal · e5')
 await expect(tooltip).toContainText('Defeat the marked sentinel')
 await expect(tooltip).toContainText('not a terrain bonus')
 await expect(square(page,'e5')).toHaveAttribute('aria-describedby','cm-unit-hover')
 await square(page,'c2').hover()
 await page.waitForTimeout(300)
 await expect(tooltip).toBeHidden()
 await expect(tooltip).toBeVisible({timeout:500})
 await expect(tooltip).toContainText('Stone wall')
 await expect(tooltip).toContainText('Hares can jump over it')
 await square(page,'d3').hover()
 await expect(tooltip).toBeHidden()
 await expect(tooltip).toBeVisible({timeout:800})
 await expect(tooltip).toContainText('Roots the shooter')
 await square(page,'h4').hover()
 await expect(tooltip).toBeHidden()
 await expect(square(page,'d3')).not.toHaveAttribute('aria-describedby')
})

test('occupied objectives keep the animal card and add square details; keyboard focus also explains terrain',async({page})=>{
 await boot(page,'crossing')
 await square(page,'d1').hover()
 const tooltip=page.locator('#cm-unit-hover')
 await expect(tooltip).toBeVisible({timeout:900})
 await expect(tooltip.locator('.tcg-unit-card')).toBeVisible()
 await expect(tooltip).toContainText('Leaving this square loses the encounter')
 await page.keyboard.press('Escape')
 await expect(tooltip).toBeHidden()
 await page.mouse.move(5,5)
 await square(page,'d1').focus()
 await expect(tooltip).toBeVisible({timeout:900})
 await expect(tooltip).toContainText('Encounter goal · d1')
})

test('temporary effects explain duration and hover never intercepts the next press',async({page})=>{
 await boot(page)
 await page.evaluate(()=>(window as any).checkmate.dispatch({type:'burn',player:'w',cardId:'w-enc-support-2',sourceUnitId:'w-unit-8',targetSquare:'d4'}))
 await square(page,'d4').hover()
 const tooltip=page.locator('#cm-unit-hover')
 await expect(tooltip).toBeVisible({timeout:900})
 await expect(tooltip).toContainText('Smoke Veil')
 await expect(tooltip).toContainText('sliding captures')
 await expect(tooltip).toContainText('Ivory’s next turn')
 await expect(tooltip).toHaveCSS('pointer-events','none')
 await page.mouse.down()
 await expect(tooltip).toBeHidden()
 await page.mouse.up()
})

test('phone tap explains an empty goal without opening a modal or spending an action',async({browser})=>{
 const context=await browser.newContext({viewport:{width:390,height:844},isMobile:true,hasTouch:true,reducedMotion:'reduce'})
 const page=await context.newPage()
 await boot(page)
 await square(page,'e5').tap()
 const tooltip=page.locator('#cm-unit-hover')
 await expect(tooltip).toBeVisible({timeout:900})
 await expect(tooltip).toContainText('Encounter goal · e5')
 const box=await tooltip.boundingBox()
 expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(390)
 expect(await page.locator('dialog[open]').count()).toBe(0)
 expect(await page.evaluate(()=>(window as any).checkmate.state.log.length)).toBe(0)
 await page.screenshot({path:'review/field-hover-phone.png'})
 await context.close()
})
